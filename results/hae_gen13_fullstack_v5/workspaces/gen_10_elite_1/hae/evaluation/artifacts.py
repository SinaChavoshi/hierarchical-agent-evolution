"""
Canonical definition of what counts as a produced artifact.

This module centralizes the logic for filtering workspace files to distinguish
between:
1. Genuinely agent-authored files.
2. Machine-generated files (caches, virtualenvs, build artifacts).
3. Malformed files (paths corrupted by markdown formatting or invalid characters).

Before this module, inconsistent filtering led to significant inflation of
reported file counts (42-59%) due to inclusion of junk files like
`.pytest_cache/CACHEDIR.TAG`, `__pycache__` entries, and paths with leaked
markdown syntax (e.g., `file.py**`).
"""

from typing import Dict, Tuple, Iterable

# Directories that are typically generated by tools or environments and should
# not be counted as agent-authored artifacts.
EXCLUDED_DIR_SEGMENTS = (
    '.pytest_cache',
    '__pycache__',
    'venv',
    '.venv',
    '.git',
    '.mypy_cache',
    '.ruff_cache',
    '.tox',
    'node_modules',
    '.ipynb_checkpoints'
)

# Directory suffixes that indicate build metadata or package info directories.
EXCLUDED_DIR_SUFFIXES = (
    '.egg-info',
    '.dist-info'
)


def is_generated_path(path: str) -> bool:
    """
    True if the path lives inside a machine-generated directory.
    
    Checks if any segment of the path matches EXCLUDED_DIR_SEGMENTS or if any
    directory segment ends with a suffix in EXCLUDED_DIR_SUFFIXES.
    """
    if not path:
        return False
        
    # Normalize separators to forward slash for consistent splitting
    # Handle both Windows and Unix style paths
    normalized_path = path.replace('\\', '/')
    
    # Split into segments. 
    # We check all segments. If a file is named `__pycache__` it's weird, but usually 
    # these are directories. The spec says "lives inside".
    # However, simple segment matching is robust.
    segments = normalized_path.split('/')
    
    for segment in segments:
        if not segment:
            continue
        if segment in EXCLUDED_DIR_SEGMENTS:
            return True
        if any(segment.endswith(suffix) for suffix in EXCLUDED_DIR_SUFFIXES):
            return True
            
    return False


def is_malformed_path(path: str) -> bool:
    """
    True if markdown formatting, stray whitespace, or invalid punctuation leaked into the filename.

    Agents emit paths through a ReAct text protocol, so bold markers (`*`),
    backticks (`` ` ``), leading/trailing whitespace, trailing dots (`.`) or
    tildes (`~`), or leading hyphens (`-`) periodically survive into `write_file`
    calls. The resulting files are unusable -- `routing.py**` or `notes.` is not
    valid -- so any path containing `*` or `` ` ``, leading/trailing whitespace,
    starting with `-`, or ending with `.` or `~` is malformed.
    """
    if not path:
        return False
        
    # Check for leading/trailing whitespace
    if path != path.strip():
        return True
        
    # Check for markdown characters anywhere in the path
    if '*' in path or '`' in path:
        return True
        
    # Check for leading hyphen
    if path.startswith('-'):
        return True
        
    # Check for trailing dot or tilde
    if path.endswith('.') or path.endswith('~'):
        return True
        
    return False


def sanitize_path(path: str) -> str:
    """
    Strips markdown decoration from an agent-supplied path.

    Applied at write time so the artifact lands at its intended location rather
    than being silently created with a broken name.
    """
    if not path:
        return path
        
    # Strip leading/trailing whitespace
    sanitized = path.strip()
    
    # Remove markdown bold/italic markers and backticks
    # We remove them entirely as they are decoration, not part of the filename
    sanitized = sanitized.replace('*', '')
    sanitized = sanitized.replace('`', '')
    
    # Handle leading hyphens? The spec says sanitize strips markdown decoration.
    # Leading hyphens are considered malformed, but sanitization usually implies
    # cleaning up the "noise". However, a leading hyphen might be intentional 
    # (e.g. hidden file or specific naming convention) but the spec says 
    # "leading hyphens ... are malformed". 
    # Usually sanitize_path is used to FIX the path. 
    # If we strip leading hyphens, we might break valid relative paths or 
    # specific conventions, but given the context of "markdown decoration",
    # and that `-` is listed as malformed, we should probably strip it if it's 
    # clearly an artifact of formatting. 
    # However, standard sanitization often just removes the obvious markdown.
    # Let's look at the malformed definition: "starting with -".
    # If we sanitize, we should probably remove the leading hyphen if it's 
    # considered noise. But wait, `sanitize_path` is applied at write time.
    # If I write `-file.txt`, it's malformed. If I sanitize it, should it become `file.txt`?
    # The docstring says "Strips markdown decoration". A leading hyphen isn't 
    # strictly markdown decoration (like `*` or `` ` ``), but it is listed as 
    # malformed. 
    # Let's stick to removing the explicit markdown chars and whitespace.
    # If the path starts with '-', it's malformed. Sanitizing it might involve 
    # stripping it to make it valid. Let's assume yes, to make it "usable".
    if sanitized.startswith('-'):
        sanitized = sanitized[1:]
        
    # Handle trailing dots or tildes?
    # "ending with . or ~" is malformed.
    # Sanitizing should likely remove them to make the file valid.
    while sanitized.endswith('.') or sanitized.endswith('~'):
        sanitized = sanitized[:-1]
        
    return sanitized


def filter_bundle(bundle: Dict[str, str]) -> Dict[str, str]:
    """
    Returns only genuinely agent-authored files from a path->content map.
    
    Filters out generated paths and malformed paths.
    """
    filtered = {}
    for path, content in bundle.items():
        if is_generated_path(path):
            continue
        if is_malformed_path(path):
            continue
        filtered[path] = content
    return filtered


def partition_bundle(bundle: Dict[str, str]) -> Tuple[Dict[str, str], Dict[str, str], Dict[str, str]]:
    """
    Splits a bundle into (authored, generated, malformed) for reporting.
    
    Returns:
        Tuple of three dicts:
        1. authored: Files that are neither generated nor malformed.
        2. generated: Files that are generated (regardless of malformed status? 
           Usually generated takes precedence or they are disjoint. 
           The spec implies distinct categories. 
           If a file is in `__pycache__` AND has a `*`, is it generated or malformed?
           Usually, if it's in a generated dir, it's generated. 
           Let's check generated first. If generated, put in generated.
           Else if malformed, put in malformed.
           Else put in authored.
        )
    """
    authored = {}
    generated = {}
    malformed = {}
    
    for path, content in bundle.items():
        if is_generated_path(path):
            generated[path] = content
        elif is_malformed_path(path):
            malformed[path] = content
        else:
            authored[path] = content
            
    return authored, generated, malformed


def count_source_files(bundle: Dict[str, str], suffixes: Iterable[str] = ('.py',)) -> int:
    """
    Counts authored files matching the given suffixes.
    
    Only counts files that pass the filter (not generated, not malformed)
    and end with one of the specified suffixes.
    """
    count = 0
    for path in bundle:
        if is_generated_path(path):
            continue
        if is_malformed_path(path):
            continue
        
        # Check suffix
        # Normalize path for suffix check? 
        # Usually suffixes are checked against the filename part.
        # But simple endswith on the full path works for standard extensions.
        if any(path.endswith(suffix) for suffix in suffixes):
            count += 1
            
    return count