"""
hae/evaluation/verification_loop.py

Generation 11 capability: in-loop ground-truth verification.

This module closes the loop between agent execution and evaluation scoring.
It provides a `VerificationLoop` that allows agents to request a real
verification report from the `ExecutionHarness` during their run, subject to
a strict budget.

Key Design Principles:
1. **Ground Truth**: The report is generated by the same `ExecutionHarness`
   used for final scoring. No drift between "practice" and "exam".
2. **Rate Limiting**: Verification is expensive (installs, runs tests). A
   small budget prevents agents from spinning on the tool and preserves the
   signal that "getting it right the first time" is better than "iterating".
3. **No Coaching**: The report states *what* is wrong (tracebacks, gate
   failures) but never *how* to fix it. Selection pressure comes from the
   population, not the harness.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

# Import dependencies from parallel modules
# These are assumed to be available in the environment as per the spec
try:
    from hae.evaluation.artifacts import filter_bundle
except ImportError:
    # Fallback for isolated testing if artifacts.py is not yet present
    def filter_bundle(bundle: Dict[str, str]) -> Dict[str, str]:
        return bundle

try:
    from hae.evaluation.harness import ExecutionHarness, PASSED, FAILED, SKIPPED
except ImportError:
    # Fallbacks for isolated testing
    PASSED = 'passed'
    FAILED = 'failed'
    SKIPPED = 'skipped'
    
    class ExecutionHarness:
        def __init__(self, timeout_s: int = 60):
            self.timeout_s = timeout_s
        def verify_bundle(self, bundle: Dict[str, str], source: str = 'bundle'):
            raise NotImplementedError("ExecutionHarness not available")

logger = logging.getLogger(__name__)

# Constants
DEFAULT_VERIFY_BUDGET = 3
_MAX_DETAIL_CHARS = 400

# Gate names in order of execution/reporting
GATE_NAMES = ("syntax", "build", "smoke", "tests", "telemetry")

# Coaching phrases that must NEVER appear in the report
COACHING_PHRASES = [
    "you should",
    "try adding",
    "rewrite it as",
    "suggestion:",
]

VERIFY_TOOL_GUIDE = (
    '- To check your work against the REAL grading gates:\n'
    '  Action: verify\n'
    '  This parses, installs, imports, tests and inspects your workspace with\n'
    '  the same harness that will score your firm, and returns the verdict.\n'
    '  It is expensive and strictly limited -- you get a small number of\n'
    '  attempts for the whole assignment, so write your code first and verify\n'
    '  when you believe it is complete.\n'
    '  Note: a gate reported as SKIP was not evaluated and earns no credit.\n'
    '  Only PASS counts.\n'
)


@dataclass
class VerifyAttempt:
    """One verification call, recorded for the scorecard."""
    turn: int
    agent_role: str
    gate_status: Dict[str, str] = field(default_factory=dict)
    passed_count: int = 0
    evaluable_count: int = 0
    authored_files: int = 0


class VerificationLoop:
    """Runs the real execution harness against a live workspace, on request.

    Holds the per-firm verify budget and the attempt history, so a scorecard
    can report not just the final gate state but how many attempts it took --
    a firm that verifies once and passes is measurably different from one that
    needed three rounds.
    """

    def __init__(self, workspace: Any, budget: int = DEFAULT_VERIFY_BUDGET, timeout_s: int = 45):
        """
        Args:
            workspace: The live agent workspace object. Must support `export_bundle()`.
            budget: Number of verify calls allowed.
            timeout_s: Timeout for the underlying harness execution.
        """
        self.workspace = workspace
        self.budget = budget
        self.timeout_s = timeout_s
        self.harness = ExecutionHarness(timeout_s=timeout_s)
        
        self.used = 0
        self.attempts: List[VerifyAttempt] = []

    @property
    def remaining(self) -> int:
        """Number of verification attempts remaining."""
        return max(0, self.budget - self.used)

    def verify(self, turn: int = 0, agent_role: str = '') -> str:
        """Runs every gate and returns an agent-readable report.

        The string is what lands in the agent's context, so it is terse by
        design.
        """
        # 1. Check Budget
        if self.remaining <= 0:
            return "BUDGET EXHAUSTED"

        # 2. Get Workspace Bundle
        try:
            raw_bundle = self.workspace.export_bundle()
        except Exception:
            raw_bundle = {}
        
        # Filter out generated/malformed files
        bundle = filter_bundle(raw_bundle)
        file_count = len(bundle)

        # 3. Handle Empty Workspace
        if file_count == 0:
            self.used += 1
            return (
                f"No files have been authored yet. Nothing to verify. "
                f"({self.remaining} verification attempt(s) remaining.)"
            )

        # 4. Run Harness
        self.used += 1
        try:
            report = self.harness.verify_bundle(bundle)
        except Exception as e:
            # If the harness itself crashes, we treat it as a failure state
            # but we still need to return a string.
            logger.exception("Harness verification failed")
            return f"Verification failed due to internal error: {e}"

        # 5. Process Results
        gate_status = report.gate_status
        gate_detail = report.gate_detail
        
        # Count passed and evaluable gates
        passed_count = 0
        evaluable_count = 0
        
        for name in GATE_NAMES:
            status = gate_status.get(name, SKIPPED)
            if status != SKIPPED:
                evaluable_count += 1
                if status == PASSED:
                    passed_count += 1

        # Record Attempt
        attempt = VerifyAttempt(
            turn=turn,
            agent_role=agent_role,
            gate_status=gate_status,
            passed_count=passed_count,
            evaluable_count=evaluable_count,
            authored_files=file_count
        )
        self.attempts.append(attempt)

        # 6. Format Report
        return self._format_report(report, passed_count, evaluable_count, file_count)

    def _format_report(self, report: Any, passed_count: int, evaluable_count: int, file_count: int) -> str:
        """Formats the verification report string."""
        lines = []
        
        # Header
        lines.append(f"{passed_count}/{evaluable_count} evaluable gate(s) passing across {file_count} authored file(s).")
        
        # Gate Details
        gate_status = report.gate_status
        gate_detail = report.gate_detail
        
        for name in GATE_NAMES:
            status = gate_status.get(name, SKIPPED)
            detail = gate_detail.get(name, "")
            
            # Truncate detail
            if len(detail) > _MAX_DETAIL_CHARS:
                detail = detail[:_MAX_DETAIL_CHARS] + "..."
            
            # Map status to display string
            if status == PASSED:
                display_status = "PASS"
            elif status == FAILED:
                display_status = "FAIL"
            else:
                display_status = "SKIP"
            
            lines.append(f"  [{display_status}] {name}: {detail}")
            
            # Specific requirement: If syntax failed, include explicit message
            if name == "syntax" and status == FAILED:
                lines.append("A file does not parse.")

        # Footer / Disclaimer
        lines.append("SKIP means the gate could not be evaluated in this environment (usually an uninstalled third-party package). A skip is not a pass and earns no credit.")
        lines.append(f"({self.remaining} verification attempt(s) remaining.)")
        
        report_str = "\n".join(lines)
        
        # Safety check: Ensure no coaching phrases
        lower_report = report_str.lower()
        for phrase in COACHING_PHRASES:
            if phrase in lower_report:
                # This should theoretically never happen if harness details are clean,
                # but we enforce the contract strictly.
                logger.warning(f"Coaching phrase '{phrase}' detected in report. Sanitizing.")
                # Simple sanitization: replace with generic text
                report_str = report_str.replace(phrase, "[redacted]")
                
        return report_str

    def summary(self) -> Dict[str, Any]:
        """Verification history for the scorecard."""
        if not self.attempts:
            best_passed = 0
            final_gate_status = {}
            converged = False
        else:
            best_passed = max(a.passed_count for a in self.attempts)
            final_attempt = self.attempts[-1]
            final_gate_status = final_attempt.gate_status
            # Converged if the final attempt's passed count is at least the best seen so far
            # (which implies it didn't regress from the peak, or is the peak)
            converged = bool(final_attempt.passed_count >= best_passed)

        attempts_data = []
        for a in self.attempts:
            attempts_data.append({
                "turn": a.turn,
                "agent_role": a.agent_role,
                "gate_status": a.gate_status,
                "passed": a.passed_count,
                "evaluable": a.evaluable_count,
                "authored_files": a.authored_files
            })

        return {
            "budget": self.budget,
            "used": self.used,
            "attempt_count": len(self.attempts),
            "best_passed_count": best_passed,
            "final_gate_status": final_gate_status,
            "converged": converged,
            "attempts": attempts_data
        }