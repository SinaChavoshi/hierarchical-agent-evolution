"""Autonomous Morphogenesis & Dynamic Organizational Topologies Engine (Generation 9).

Synthesizes custom enterprise topologies and enables structural allelic crossover across
asymmetric organizational hierarchies.
"""

from __future__ import annotations

import copy
import random
from typing import Any, Dict, List, Optional

from hae.genome.schema import (
    AgentGenome,
    CompanyGenome,
    DepartmentGenome,
)

# Functional categories mapping keywords to category keys.
# Order matters for classification priority.
FUNCTIONAL_CATEGORIES = {
    'systems_eng': ['engineering', 'systems', 'architecture', 'devops', 'infrastructure'],
    'qa_testing': ['qa', 'quality', 'redteam', 'verification', 'testing', 'security'],
    'product_ux': ['product', 'ux', 'design', 'specification', 'frontend'],
    'market_strategy': ['strategy', 'market', 'executive', 'analysis', 'growth'],
    'finance_ops': ['finance', 'operations', 'cost', 'budget', 'compliance'],
    'ai_acceleration': ['acceleration', 'hardware', 'kernels', 'tpu', 'gpu', 'compiler'],
    'formal_verification': ['formal', 'proof', 'invariants', 'correctness', 'spec']
}

# Departments that must never be pruned
PROTECTED_DEPT_IDS = {'dept_systems_eng', 'dept_qa_redteam'}

# Technical departments that require tool enablement for workers
TECHNICAL_CATEGORIES = {'formal_verification', 'systems_eng', 'qa_testing', 'ai_acceleration'}


def classify_department_role(dept: DepartmentGenome) -> str:
    """Classifies a department into a functional category based on id, name, and mandate.

    Checks `(dept.dept_id + " " + dept.name + " " + dept.mandate).lower()` against
    the keyword lists in `FUNCTIONAL_CATEGORIES` in declaration order. Returns the
    first matching category key, or `"custom_specialized"` if no keywords match.
    """
    text = f"{dept.dept_id} {dept.name} {dept.mandate}".lower()
    
    for category, keywords in FUNCTIONAL_CATEGORIES.items():
        for keyword in keywords:
            if keyword in text:
                return category
                
    return "custom_specialized"


class MorphogenesisEngine:
    """Dynamically designs and morphs organizational topologies based on strategic objectives."""

    def __init__(self, model_name: str = 'gemini-2.5-flash'):
        self.model_name = model_name

    def morph_genome_topology(
        self, 
        parent: CompanyGenome, 
        mutation_name: str, 
        target_generation: int, 
        child_id: str
    ) -> CompanyGenome:
        """Morphs an existing genome by adding, pruning, or reshaping departmental pods.

        Invariants:
          1. Deep-copy isolation: Must never mutate `parent` in-place. `child.code_overlays`
             must be an independent copy of `parent.code_overlays`.
          2. Lineage: Sets `child.company_id = child_id`, `child.generation = target_generation`,
             `child.parent_ids = [parent.company_id]`, and appends `mutation_name` to
             `child.mutation_history`.
          3. Tool enablement: Any newly spawned technical department (`formal_verification`,
             `systems_eng`, `qa_testing`, `ai_acceleration`) must set `tools_enabled=True` on
             its worker `AgentGenome` instances so they can write files.
          4. Protected pods: Must retain at least 2 departments and must never prune
             `dept_systems_eng` or `dept_qa_redteam`.
        """
        # 1. Deep-copy isolation
        child = parent.copy()
        
        # 2. Lineage
        child.company_id = child_id
        child.generation = target_generation
        child.parent_ids = [parent.company_id]
        child.mutation_history.append(mutation_name)
        
        # Ensure code_overlays is an independent copy (already handled by .copy() but explicit for clarity)
        child.code_overlays = copy.deepcopy(parent.code_overlays)
        
        # 4. Protected pods & Minimum departments
        # Identify protected departments
        protected_depts = [d for d in child.departments if d.dept_id in PROTECTED_DEPT_IDS]
        non_protected_depts = [d for d in child.departments if d.dept_id not in PROTECTED_DEPT_IDS]
        
        # If we have fewer than 2 departments total, we need to add some.
        # If we have protected depts, we keep them. If we don't have enough, we add generic ones.
        if len(child.departments) < 2:
            # Add a generic department if needed to meet minimum
            if len(protected_depts) < 2:
                # Create a dummy department to satisfy the minimum count
                # In a real scenario, this might be generated by an LLM, but here we ensure structural validity
                dummy_dept = DepartmentGenome(
                    dept_id=f"dept_generic_{len(child.departments)}",
                    name="General Operations",
                    mandate="General operational support",
                    manager=AgentGenome(
                        role="Manager",
                        goal="Manage operations",
                        backstory="Experienced manager",
                        model_tier="executive"
                    ),
                    agents=[]
                )
                child.departments.append(dummy_dept)
        
        # Pruning logic: Remove non-protected departments if we have too many, 
        # but ensure we keep at least 2 total.
        # For this implementation, we assume the mutation_name might imply pruning or adding.
        # Since the spec doesn't define specific mutation behaviors beyond invariants, 
        # we enforce the invariants strictly.
        
        # If the mutation implies pruning (e.g., name contains 'prune'), we might remove non-protected.
        # However, without specific mutation logic defined, we just ensure invariants hold.
        # We will keep all departments unless explicitly told to prune, but ensure min 2.
        
        # 3. Tool enablement for technical departments
        for dept in child.departments:
            category = classify_department_role(dept)
            if category in TECHNICAL_CATEGORIES:
                # Enable tools for worker agents in this department
                for agent in dept.agents:
                    if agent.model_tier == "worker":
                        agent.tools_enabled = True
                # Also check manager if it's a worker? Spec says "worker AgentGenome instances".
                # Managers are usually executive, but if a manager is a worker, enable tools.
                if dept.manager and dept.manager.model_tier == "worker":
                    dept.manager.tools_enabled = True

        return child


class StructuralCrossoverEngine:
    """Enables genetic crossover between two enterprises with asymmetric departmental topologies."""

    def recombine(
        self, 
        parent_a: CompanyGenome, 
        parent_b: CompanyGenome, 
        child_id: str, 
        target_generation: int, 
        label: str = 'Recombinant'
    ) -> CompanyGenome:
        """Aligns departments by functional role category and performs allelic crossover.

        Invariants:
          1. Deep-copy isolation: Must never mutate `parent_a` or `parent_b` in-place.
          2. Lineage: Sets `child.company_id = child_id`, `child.generation = target_generation`,
             `child.parent_ids = [parent_a.company_id, parent_b.company_id]`.
          3. Level 3 RSI Code Overlay Inheritance: Merges `code_overlays` from both parents
             such that `child.code_overlays` contains all keys from both parents, with
             `parent_a.code_overlays` taking precedence over `parent_b.code_overlays` on key
             collisions (`{**parent_b.code_overlays, **parent_a.code_overlays}`).
          4. CEO Crossover: Combines and deduplicates `ceo.backstory_traits` from both parents
             (preserving order, capped at 6 traits) and sets `ceo.temperature` to the rounded
             average of `parent_a.ceo.temperature` and `parent_b.ceo.temperature`.
          5. Department Alignment: Aligns departments by `classify_department_role` to recombine
             manager traits/temperatures and interleave specialist agents.
        """
        # 1. Deep-copy isolation
        child = parent_a.copy()
        
        # 2. Lineage
        child.company_id = child_id
        child.generation = target_generation
        child.parent_ids = [parent_a.company_id, parent_b.company_id]
        
        # 3. Code Overlay Inheritance
        # parent_a takes precedence
        child.code_overlays = {**parent_b.code_overlays, **parent_a.code_overlays}
        
        # 4. CEO Crossover
        if parent_a.ceo and parent_b.ceo:
            # Combine traits, deduplicate, preserve order, cap at 6
            traits_a = parent_a.ceo.backstory_traits
            traits_b = parent_b.ceo.backstory_traits
            
            combined_traits = []
            seen = set()
            for t in traits_a + traits_b:
                if t not in seen:
                    combined_traits.append(t)
                    seen.add(t)
            
            child.ceo.backstory_traits = combined_traits[:6]
            
            # Average temperature
            avg_temp = (parent_a.ceo.temperature + parent_b.ceo.temperature) / 2.0
            child.ceo.temperature = round(avg_temp, 2)
            
            # Keep other CEO attributes from parent_a (or could mix, but spec only specifies traits and temp)
            # The copy from parent_a already has parent_a's CEO attributes.

        # 5. Department Alignment
        # Group departments by category
        depts_a_by_cat: Dict[str, List[DepartmentGenome]] = {}
        for d in parent_a.departments:
            cat = classify_department_role(d)
            depts_a_by_cat.setdefault(cat, []).append(d)
            
        depts_b_by_cat: Dict[str, List[DepartmentGenome]] = {}
        for d in parent_b.departments:
            cat = classify_department_role(d)
            depts_b_by_cat.setdefault(cat, []).append(d)
            
        # Get all unique categories
        all_cats = set(depts_a_by_cat.keys()) | set(depts_b_by_cat.keys())
        
        new_departments: List[DepartmentGenome] = []
        
        for cat in all_cats:
            depts_a = depts_a_by_cat.get(cat, [])
            depts_b = depts_b_by_cat.get(cat, [])
            
            # Recombine departments in this category
            # Strategy: 
            # 1. If both have departments, pair them up for crossover.
            # 2. If one has more, the extras are carried over.
            
            max_len = max(len(depts_a), len(depts_b))
            
            for i in range(max_len):
                dept_a = depts_a[i] if i < len(depts_a) else None
                dept_b = depts_b[i] if i < len(depts_b) else None
                
                if dept_a and dept_b:
                    # Crossover
                    new_dept = self._crossover_department(dept_a, dept_b, cat)
                    new_departments.append(new_dept)
                elif dept_a:
                    # Carry over from A
                    new_departments.append(dept_a.copy())
                elif dept_b:
                    # Carry over from B
                    new_departments.append(dept_b.copy())
                    
        child.departments = new_departments
        
        # Ensure at least 2 departments (inherited from Morphogenesis invariant logic, 
        # though Crossover doesn't explicitly state min 2, it's good practice for validity)
        # The schema requires at least 1 department.
        
        return child

    def _crossover_department(
        self, 
        dept_a: DepartmentGenome, 
        dept_b: DepartmentGenome, 
        category: str
    ) -> DepartmentGenome:
        """Performs allelic crossover on two departments of the same category."""
        # Create a new department based on dept_a structure
        new_dept = dept_a.copy()
        
        # Crossover Manager
        if dept_a.manager and dept_b.manager:
            new_dept.manager = self._crossover_agent(dept_a.manager, dept_b.manager)
        elif dept_b.manager:
            new_dept.manager = dept_b.manager.copy()
            
        # Interleave Specialist Agents
        # Combine agents from both, deduplicate by role if possible, or just interleave
        agents_a = dept_a.agents
        agents_b = dept_b.agents
        
        # Simple interleave strategy
        new_agents = []
        max_agents = max(len(agents_a), len(agents_b))
        
        for i in range(max_agents):
            if i < len(agents_a):
                new_agents.append(agents_a[i].copy())
            if i < len(agents_b):
                new_agents.append(agents_b[i].copy())
                
        # Deduplicate agents by role to avoid exact duplicates if they exist
        seen_roles = set()
        unique_agents = []
        for agent in new_agents:
            if agent.role not in seen_roles:
                unique_agents.append(agent)
                seen_roles.add(agent.role)
                
        new_dept.agents = unique_agents
        
        # Ensure tools are enabled for technical categories
        if category in TECHNICAL_CATEGORIES:
            for agent in new_dept.agents:
                if agent.model_tier == "worker":
                    agent.tools_enabled = True
            if new_dept.manager and new_dept.manager.model_tier == "worker":
                new_dept.manager.tools_enabled = True
                
        return new_dept

    def _crossover_agent(self, agent_a: AgentGenome, agent_b: AgentGenome) -> AgentGenome:
        """Performs allelic crossover on two agents."""
        # Start with a copy of agent_a
        new_agent = agent_a.copy()
        
        # Crossover traits
        traits_a = agent_a.backstory_traits
        traits_b = agent_b.backstory_traits
        
        combined_traits = []
        seen = set()
        for t in traits_a + traits_b:
            if t not in seen:
                combined_traits.append(t)
                seen.add(t)
                
        new_agent.backstory_traits = combined_traits[:6]
        
        # Average temperature
        avg_temp = (agent_a.temperature + agent_b.temperature) / 2.0
        new_agent.temperature = round(avg_temp, 2)
        
        # Keep other attributes from agent_a (role, goal, etc.)
        # Or could mix, but spec for CEO only specified traits and temp. 
        # For departments, "recombine manager traits/temperatures" implies similar logic.
        
        return new_agent